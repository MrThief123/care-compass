#!/usr/bin/env node
// [INT-05] Generates docs/security/PERMISSION_MATRIX.md from the live local Supabase stack and
// the dashboard route tree, rather than a hand-maintained table that could drift from reality.
//
//   supabase start               (if not already running)
//   node scripts/generate-permission-matrix.mjs
//
// Two sources, same enumerate-don't-list approach as the regression tests themselves:
//   - RLS status per public table: queried from pg_catalog inside the local `supabase_db_*`
//     Docker container (T-01, supabase/tests/access_control_regression.test.sql).
//   - Dashboard route -> guarding role: scanned from src/app's three role route groups, same
//     logic as T-02's route-coverage test (tests/integration/shared-access-control-regression.test.ts).
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import path, { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function findDbContainer() {
  const names = execFileSync("docker", [
    "ps",
    "--filter",
    "name=supabase_db_",
    "--format",
    "{{.Names}}",
  ])
    .toString()
    .trim()
    .split("\n")
    .filter(Boolean);
  if (names.length === 0) {
    throw new Error("No running supabase_db_* container found — run `supabase start` first.");
  }
  return names[0];
}

function queryRlsStatus(container) {
  const out = execFileSync("docker", [
    "exec",
    container,
    "psql",
    "-U",
    "postgres",
    "-d",
    "postgres",
    "-t",
    "-A",
    "-F,",
    "-c",
    "select c.relname, c.relrowsecurity from pg_class c " +
      "join pg_namespace n on n.oid = c.relnamespace " +
      "where n.nspname = 'public' and c.relkind in ('r','p') order by 1;",
  ]).toString();

  return out
    .trim()
    .split("\n")
    .filter(Boolean)
    .map((line) => {
      const [table, enabled] = line.split(",");
      return { table, rlsEnabled: enabled === "t" };
    });
}

function findPageFiles(dir) {
  const found = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      found.push(...findPageFiles(full));
    } else if (entry === "page.tsx") {
      found.push(full);
    }
  }
  return found;
}

function ancestorLayouts(pageDir, groupDir) {
  const layouts = [];
  let current = pageDir;
  for (;;) {
    const candidate = join(current, "layout.tsx");
    try {
      if (statSync(candidate).isFile()) layouts.push(candidate);
    } catch {
      // no layout at this level
    }
    if (current === groupDir) break;
    current = dirname(current);
  }
  return layouts;
}

function guardsRole(source, role) {
  return (
    new RegExp(`getCurrentUser\\(\\s*["']${role}["']`).test(source) ||
    new RegExp(`evaluateRoleGuard\\([^)]*["']${role}["']`).test(source)
  );
}

function pageRoute(pagePath, appRoot) {
  // src/app/(admin)/admin/staff/page.tsx -> /admin/staff
  const rel = relative(appRoot, dirname(pagePath));
  return "/" + rel.replace(/\([^/]*\)\/?/g, "").replace(/\\/g, "/");
}

function collectRoutes() {
  const appRoot = join(ROOT, "src", "app");
  const roleGroups = [
    { dir: join(appRoot, "(admin)"), role: "admin" },
    { dir: join(appRoot, "(carer)"), role: "carer" },
    { dir: join(appRoot, "(family)"), role: "family" },
  ];

  return roleGroups.flatMap(({ dir, role }) =>
    findPageFiles(dir)
      .map((pagePath) => {
        const filesToCheck = [pagePath, ...ancestorLayouts(dirname(pagePath), dir)];
        const guarded = filesToCheck.some((file) => guardsRole(readFileSync(file, "utf-8"), role));
        return { route: pageRoute(pagePath, appRoot), role, guarded };
      })
      .sort((a, b) => a.route.localeCompare(b.route)),
  );
}

function renderMarkdown({ rls, routes, generatedAt }) {
  const rlsRows = rls
    .map((r) => `| \`${r.table}\` | ${r.rlsEnabled ? "✅ enabled" : "❌ MISSING"} |`)
    .join("\n");
  const routeRows = routes
    .map((r) => `| \`${r.route}\` | ${r.role} | ${r.guarded ? "✅ guarded" : "❌ UNGUARDED"} |`)
    .join("\n");
  const rlsGaps = rls.filter((r) => !r.rlsEnabled).length;
  const routeGaps = routes.filter((r) => !r.guarded).length;

  return `# Permission matrix

Generated by \`node scripts/generate-permission-matrix.mjs\` on ${generatedAt} — do not edit by
hand (INT-05, PRD.md Scope: "docs/security/PERMISSION_MATRIX.md generated from tests").
Re-run it after any migration or route change and commit the result.

Source of truth: \`supabase/tests/access_control_regression.test.sql\` (AC-01, pgTAP) and
\`tests/integration/shared-access-control-regression.test.ts\` (AC-02, route coverage).

## Row Level Security — every table in schema \`public\`

${rlsGaps === 0 ? "All tables have RLS enabled." : `**${rlsGaps} table(s) missing RLS — fix before merging.**`}

| Table | Row Level Security |
|---|---|
${rlsRows}

## Dashboard routes — guarded per role

${routeGaps === 0 ? "Every dashboard page sits under a guarding layout for its role." : `**${routeGaps} page(s) unguarded — fix before merging.**`}

| Route | Role | Guard |
|---|---|---|
${routeRows}
`;
}

const container = findDbContainer();
const rls = queryRlsStatus(container);
const routes = collectRoutes();
const markdown = renderMarkdown({
  rls,
  routes,
  generatedAt: new Date().toISOString().slice(0, 10),
});

const outDir = join(ROOT, "docs", "security");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "PERMISSION_MATRIX.md"), markdown);

const rlsGaps = rls.filter((r) => !r.rlsEnabled).length;
const routeGaps = routes.filter((r) => !r.guarded).length;
console.log(
  `docs/security/PERMISSION_MATRIX.md written: ${rls.length} tables (${rlsGaps} gaps), ${routes.length} routes (${routeGaps} gaps).`,
);
if (rlsGaps > 0 || routeGaps > 0) process.exitCode = 1;
